import { test, expect } from '@playwright/test';
import { task3Fixture, check } from '../local-supabase.mjs';

const today = new Intl.DateTimeFormat('sv-SE', { timeZone:'Asia/Jakarta', year:'numeric', month:'2-digit', day:'2-digit' }).format(new Date());
const tomorrow = new Date(Date.parse(`${today}T00:00:00Z`) + 86400000).toISOString().slice(0,10);
async function assertPdf(download, filename) {
  expect(download.suggestedFilename()).toMatch(filename);
  const stream = await download.createReadStream();
  const chunks = [];
  for await (const chunk of stream) chunks.push(chunk);
  const bytes = Buffer.concat(chunks);
  expect(bytes.subarray(0,5).toString()).toBe('%PDF-');
  return bytes;
}

test('draft, kontrak, pencairan, pembayaran dan koreksi melalui browser', async ({ browser }) => {
  const f = await task3Fixture();
  const contexts = [];
  let customer;
  try {
    const admin = await f.authUser('admin'), borrower = await f.authUser();
    const templateId = check(await admin.api.rpc('loan_create_contract_template',{p_title:'Template browser sintetis',p_body:'Perjanjian {{nama}} untuk {{pokok}}'}));
    customer = await f.customer(borrower.id);
    await f.enable();
    const category = check(await f.service.from('loan_categories').select('id').eq('is_active',true).limit(1).single());
    const context = await browser.newContext(); contexts.push(context);
    const page = await context.newPage();
    await page.goto('/login');
    await page.getByLabel('Email',{exact:true}).fill(admin.email);
    await page.getByLabel('Password',{exact:true}).fill(admin.password);
    await page.getByRole('button',{name:'Login',exact:true}).click();
    await expect(page).toHaveURL(/\/dashboard$/);
    await page.goto('/pinjaman');
    await expect(page.getByText('Buat draft pinjaman',{exact:true})).toBeVisible();
    const draft = page.getByText('Buat draft pinjaman',{exact:true}).locator('../..');
    await draft.getByRole('combobox',{name:'Nasabah',exact:true}).selectOption(customer.id);
    await draft.getByRole('combobox',{name:'Kategori',exact:true}).selectOption(category.id);
    await draft.getByLabel('Nominal pokok (Rp)').fill('1000000');
    await draft.getByLabel('Rencana tanggal pencairan').fill(today);
    await draft.getByLabel('Digunakan untuk').fill('Uji browser pinjaman sintetis');
    await draft.getByRole('combobox',{name:'Petugas penanggung jawab'}).selectOption(admin.id);
    await draft.getByLabel('Catatan (opsional)').fill('Uji catatan draft');
    await draft.getByLabel('Jatuh tempo pertama').fill(tomorrow);
    await draft.getByLabel('Jumlah angsuran').fill('3');
    await draft.getByRole('button',{name:'Tinjau jadwal'}).click();
    await expect(draft.getByText(/333\.333/)).toHaveCount(2);
    await expect(draft.getByText(/333\.334/)).toHaveCount(1);
    await draft.getByRole('button',{name:'Simpan draft'}).click();
    await expect(page.getByText('Draft pinjaman tersimpan.')).toBeVisible();
    const loan = check(await f.service.from('loans').select('id,loan_number').eq('customer_id',customer.id).single());
    f.loans.push(loan.id);
    await page.getByText('Pinjaman terbaru',{exact:true}).locator('../..').getByRole('button',{name:new RegExp(loan.loan_number)}).click();
    const detail = page.getByText('Rincian pinjaman',{exact:true}).locator('../..');
    const contract = detail.getByRole('heading',{name:'Kontrak dan pencairan'}).locator('..');
    await detail.getByLabel('Versi template').selectOption(templateId);
    await contract.getByLabel('Tanggal pencairan',{exact:true}).fill(today);
    await contract.getByLabel('Label sumber dana').fill('Dana sintetis');
    await contract.getByRole('button',{name:'Catat pencairan'}).click();
    await expect.poll(async () => check(await f.service.from('loans').select('status').eq('id',loan.id).single()).status).toBe('draft');
    await contract.getByLabel('Kontrak bertanda tangan').setInputFiles({name:'kontrak.pdf',mimeType:'application/pdf',buffer:Buffer.from('%PDF-1.4\n%synthetic contract\n%%EOF')});
    await contract.getByLabel('Saya sudah memeriksa kontrak dan tanda tangannya.').check();
    await contract.getByRole('button',{name:'Simpan kontrak'}).click();
    await expect(page.getByText('Kontrak bertanda tangan tersimpan.')).toBeVisible();
    await contract.getByLabel('Bukti pencairan opsional').setInputFiles({name:'pencairan.pdf',mimeType:'application/pdf',buffer:Buffer.from('%PDF-1.4\n%synthetic disbursement\n%%EOF')});
    await contract.getByRole('button',{name:'Catat pencairan'}).click();
    await expect(page.getByText('Pencairan tercatat.')).toBeVisible();
    await expect(page.getByText('Bukti pencairan tersimpan.')).toBeVisible();
    await expect(detail.getByRole('button',{name:'Unduh bukti pencairan'})).toBeVisible();
    await detail.getByRole('button',{name:'Bagikan ke nasabah'}).click();
    await expect(page.getByText('Akses kontrak diperbarui.')).toBeVisible();
    const staffDownload = page.waitForEvent('download');
    await detail.getByRole('button',{name:'Unduh ringkasan pencairan'}).click();
    await assertPdf(await staffDownload,/ringkasan-pencairan.*\.pdf$/);
    await expect(contract).toHaveCount(0);
    const payment = detail.getByRole('heading',{name:'Catat pembayaran'}).locator('..');
    await expect(payment).toHaveCount(1);
    await payment.getByLabel('Tanggal',{exact:true}).fill(today);
    await payment.getByLabel('Nominal (Rp)',{exact:true}).fill('250000');
    await payment.getByLabel('Catatan internal opsional').fill('Catatan internal sintetis');
    await payment.getByLabel('Lampiran bukti opsional').setInputFiles({name:'bukti.pdf',mimeType:'application/pdf',buffer:Buffer.from('%PDF-1.4\n%synthetic proof\n%%EOF')});
    await payment.getByRole('button',{name:'Konfirmasi pembayaran'}).click();
    await expect(page.getByText('Bukti pembayaran tersimpan.')).toBeVisible();
    await expect(detail.getByText('Transaksi terkonfirmasi: 1')).toBeVisible();
    await expect(detail.getByText('Angsuran lunas: 0/3')).toBeVisible();
    await expect(detail.getByText(/Sisa pokok:.*750\.000/)).toBeVisible();
    const customerContext = await browser.newContext(); contexts.push(customerContext);
    const customerPage = await customerContext.newPage();
    await customerPage.goto('/login');
    await customerPage.getByLabel('Email',{exact:true}).fill(borrower.email);
    await customerPage.getByLabel('Password',{exact:true}).fill(borrower.password);
    await customerPage.getByRole('button',{name:'Login',exact:true}).click();
    await expect(customerPage.getByRole('heading',{name:'Pinjaman Saya'})).toBeVisible();
    await expect(customerPage.getByText(loan.loan_number,{exact:true})).toBeVisible();
    await expect(customerPage.getByText('Catatan internal sintetis',{exact:true})).toHaveCount(0);
    await expect(customerPage.getByRole('button',{name:'Unduh kontrak final'})).toBeVisible();
    const customerDownload = customerPage.waitForEvent('download');
    await customerPage.getByRole('button',{name:'Unduh kartu pinjaman'}).click();
    await assertPdf(await customerDownload,/kartu-pinjaman.*\.pdf$/);
    const claim = customerPage.getByRole('heading',{name:'Kirim bukti transfer'}).locator('..');
    await claim.getByLabel('Tanggal transfer').fill(today);
    await claim.getByLabel('Nominal (Rp)',{exact:true}).fill('100000');
    await claim.getByLabel('Bukti transfer').setInputFiles([1,2,3].map(n=>({name:`bukti${n}.pdf`,mimeType:'application/pdf',buffer:Buffer.from('%PDF-1.4\n%synthetic\n%%EOF')})));
    await claim.getByRole('button',{name:'Kirim untuk diperiksa'}).click();
    await expect(customerPage.getByText('Bukti terkirim dan menunggu pemeriksaan pengurus.')).toBeVisible();
    const pending = check(await f.service.from('loan_payments').select('id').eq('loan_id',loan.id).eq('status','pending').single());
    expect(check(await f.service.from('loan_documents').select('id').eq('payment_id',pending.id))).toHaveLength(3);
    const history = detail.getByRole('heading',{name:'Riwayat pembayaran'}).locator('..');
    const receiptBefore = page.waitForEvent('download');
    await history.getByRole('button',{name:'Unduh tanda terima'}).click();
    const issued = await receiptBefore;
    await assertPdf(issued,/tanda-terima.*\.pdf$/);
    await history.getByLabel('Alasan pembatalan').fill('Koreksi uji browser');
    await history.getByRole('button',{name:'Batalkan pembayaran'}).click();
    await expect(page.getByText('Pembayaran dibatalkan.')).toBeVisible();
    await expect(detail.getByText('Transaksi terkonfirmasi: 0')).toBeVisible();
    await expect(detail.getByText(/Sisa pokok:.*1\.000\.000/)).toBeVisible();
    await expect(history.getByText(/cancelled/)).toBeVisible();
    const receiptAfter = page.waitForEvent('download');
    await history.getByRole('button',{name:'Unduh tanda terima'}).click();
    const cancelled = await receiptAfter;
    expect(cancelled.suggestedFilename()).toBe(issued.suggestedFilename());
    expect((await assertPdf(cancelled,/tanda-terima.*\.pdf$/)).toString('latin1')).toContain('DIBATALKAN');
    await page.reload();
    const queue=page.getByText('Antrean bukti pembayaran',{exact:true}).locator('../..');
    const claimRow=queue.locator('div.rounded.border.p-3').filter({hasText:loan.loan_number});
    await expect(claimRow.getByRole('button',{name:/Unduh bukti [123]/})).toHaveCount(3);
    await claimRow.getByRole('button',{name:loan.loan_number}).click();
    await expect(page.getByText('Rincian pinjaman',{exact:true})).toBeVisible();
  } finally {
    await Promise.all(contexts.map(context => context.close()));
    if (customer) {
      const loans = check(await f.service.from('loans').select('id').eq('customer_id',customer.id));
      for (const loan of loans) if (!f.loans.includes(loan.id)) f.loans.push(loan.id);
      if (f.loans.length) {
        const documents = check(await f.service.from('loan_documents').select('storage_path').in('loan_id',f.loans));
        for (const document of documents) f.objects.push(['pinjaman-jamaah-private',document.storage_path]);
      }
    }
    await f.cleanup();
  }
});
